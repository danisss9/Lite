    private static void Bump(Dictionary<string, int> counts, string key) =>
        counts[key] = counts.GetValueOrDefault(key) + 1;

    private static string FormatCounts(Dictionary<string, int> totals)
    {
        var runs = totals.GetValueOrDefault("runs");
        var pass = totals.GetValueOrDefault("pass");
        return $"{pass}/{runs} pass ({(runs == 0 ? 0 : 100.0 * pass / runs):F1}%)";
    }

    private static string Truncate(string value) =>
        value.Length <= MaxRecordedLength ? value : value[..MaxRecordedLength] + "…";

    private static void WriteArtifact(string path, Dictionary<string, int> totals,
        Dictionary<string, int> errorAgreement, Dictionary<string, (int Expected, int Reported)> specCodeStats,
        Dictionary<string, int> engineExtra, List<(string File, int Cases, Dictionary<string, int> Totals)> byFile,
        List<CaseOut> failures)
    {
        var payload = new
        {
            formatVersion = 1,
            kind = "html5-tokenizer-report",
            generatedUtc = DateTime.UtcNow.ToString("o"),
            diagnostic = true,
            totals,
            errors = new
            {
                agreement = errorAgreement,
                specCodes = specCodeStats.ToDictionary(kv => kv.Key,
                    kv => new { expected = kv.Value.Expected, reported = kv.Value.Reported }),
                engineExtra,
            },
            files = byFile.Select(f => new { file = f.File, cases = f.Cases, totals = f.Totals }),
            failures,
        };
        var options = new System.Text.Json.JsonSerializerOptions
        {
            WriteIndented = true,
            PropertyNamingPolicy = System.Text.Json.JsonNamingPolicy.CamelCase,
        };
        File.WriteAllText(path, System.Text.Json.JsonSerializer.Serialize(payload, options));
    }
