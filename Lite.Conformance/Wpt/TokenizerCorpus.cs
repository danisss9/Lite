using System.Text.Json.Nodes;
using AngleSharp.Html;
using AngleSharp.Html.Parser;
using AngleSharp.Html.Parser.Tokens;
using AngleSharp.Text;
using Lite.Conformance.Harness;

namespace Lite.Conformance.Wpt;

/// <summary>
/// The html5lib tokenizer corpus (Milestone 2): the 15 vendored .test JSON files under
/// vendor/html5lib-tests/tokenizer, run through the engine's own tokenizer with each case's
/// initial state and last-start-tag setup, comparing the emitted token stream against the
/// expected stream (adjacent Character tokens coalesced, the EOF token dropped, duplicate
/// attributes and self-closing flags honored per the format).
///
/// Parse errors are a measured secondary signal, never the pass condition: the 2014
/// Recommendation defines parse-error *occurrences* without error codes (the code vocabulary
/// is living-standard), and the engine's HtmlParseError set collapses several spec codes per
/// raise site and does not sequence them. The map below carries every spec tokenizer code the
/// corpus exercises onto the engine codes that may legitimately report it — engine sets are
/// wide where the engine discriminates by character class rather than by spec code, and empty
/// where the engine never reports the condition (several are living-standard-only input
/// checks the 2014 REC does not define). A run's errors agree when every expected code is
/// reported by some engine error and every engine error is claimed by some expected code.
///
/// The initial-state dispatch feeds the tokenizer exactly the way a real parse reaches each
/// state: the last start tag is emitted as a real tag before the state applies (the tokenizer
/// never switches state on a start tag itself), and the CDATA-section state is entered
/// through a real &lt;![CDATA[ markup declaration, because the engine has no standalone CDATA
/// mode — that is also how every document enters it.
///
/// The gate (--suite html5-tokenizer) decides every case/state run's token stream: raw pass,
/// reviewed ledger-pass (Wpt/html5-tokenizer-expectations.json, regenerated by
/// scripts/gen_html5_tokenizer_expectations.py after engine changes; reviewed entries are
/// never overwritten, stale or mismatched entries fail the gate), or the pinned U+FFFF
/// runner-exclusion. Parse-error codes are measured and reported, never gated: the 2014
/// Recommendation defines parse errors without codes.
/// </summary>
internal static class TokenizerCorpus
{
    private const int MaxRecordedLength = 400;

    private sealed record CaseOut(string File, int Index, string State, string Description,
        string Outcome, string Errors, string Signature, string Expected, string Actual);

    private sealed record LedgerEntry(string Verdict, string Clause, List<string> CorrectedOutput);

    internal const string LedgerFileName = "Wpt/html5-tokenizer-expectations.json";

    /// <summary>The case whose corpus expectation cannot be met without reworking the
    /// engine's EOF discipline: a literal U+FFFF in the input stream is indistinguishable
    /// from the tokenizer's end-of-file sentinel (Symbols.EndOfFile = Char.MaxValue), so
    /// the engine replaces it with U+FFFD. Documented in Lite.AngleSharp/README.md; the
    /// gate counts this as runner-excluded, never as decided.</summary>
    internal static readonly Dictionary<(string File, int Index), string> RunnerExclusions = new()
    {
        [("unicodeChars.test", 61)] =
            "the tokenizer's EOF sentinel (Char.MaxValue) collides with a literal U+FFFF " +
            "in the input stream; the 2014 letter keeps it verbatim, but reworking the " +
            "EOF discipline across the char-stream layer outweighs one subtest",
    };

    private static Dictionary<(string File, int Index, string State), LedgerEntry> LoadLedger(
        out int unreviewed)
    {
        var ledger = new Dictionary<(string, int, string), LedgerEntry>();
        unreviewed = 0;
        var path = ConformancePaths.Manifest(LedgerFileName);
        if (!File.Exists(path))
        {
            return ledger;
        }

        var root = JsonNode.Parse(File.ReadAllText(path))!.AsObject();
        foreach (var caseNode in root["cases"]!.AsArray())
        {
            var obj = caseNode!.AsObject();
            var reviewed = obj["reviewed"]!.GetValue<bool>();
            if (!reviewed)
            {
                unreviewed++;
                continue;
            }

            var corrected = obj["correctedOutput"]!.AsArray()
                .Select(n => n!.GetValue<string>())
                .ToList();
            ledger[(obj["file"]!.GetValue<string>(), obj["index"]!.GetValue<int>(),
                obj["state"]!.GetValue<string>())] =
                new LedgerEntry(obj["verdict"]!.GetValue<string>(), obj["clause"]!.GetValue<string>(), corrected);
        }

        return ledger;
    }

    /// <summary>The engine tokenizer configuration the corpus runs under: the DOM builder's
    /// own entity provider and the engine's parse options (no skip flags, no strict mode, no
    /// processing-instruction tokens — the 2014 letter treats &lt;? as a bogus comment). The
    /// source carries the case's setup prefixes: the last start tag as a real tag (how the
    /// tokenizer learns the name) and, for CDATA-section cases, the &lt;![CDATA[ markup
    /// declaration that is also how every real parse enters that state.</summary>
    private static HtmlTokenizer MakeTokenizer(string source, bool cdataState,
        out List<(HtmlParseError Code, int Line, int Column)> errors)
    {
        var tokenizer = new HtmlTokenizer(new TextSource(source), HtmlEntityProvider.ResolverExtended)
        {
            IsAcceptingCharacterData = cdataState,
        };
        var collected = new List<(HtmlParseError, int, int)>();
        tokenizer.Error += (_, e) => collected.Add(((HtmlParseError)e.Code, e.Position.Line, e.Position.Column));
        errors = collected;
        return tokenizer;
    }

    /// <summary>The parse-fidelity gate for the tokenizer corpus: every case/state run must
    /// end in a verified, machine-checked token-stream outcome on this build identity — a
    /// raw pass, a reviewed ledger-pass, or the pinned U+FFFF runner-exclusion. Stale
    /// (passing raw), mismatched, or open runs fail the gate. Parse-error codes are a
    /// measured secondary signal, never the gate: the 2014 Recommendation defines parse
    /// errors without codes (the code vocabulary is living-standard), and the map in this
    /// class attributes them in the report.</summary>
    public static int RunGate(string? reportPath) => Run(reportPath, gate: true);

    public static int Run(string? reportPath, bool gate = false)
    {
        var directory = Path.Combine(ConformancePaths.Vendor, "html5lib-tests", "tokenizer");
        if (!Directory.Exists(directory))
        {
            Console.Error.WriteLine(
                $"html5lib tokenizer corpus not found at {directory}; run scripts/fetch-tests.ps1 first.");
            return 2;
        }

        var ledger = LoadLedger(out var unreviewedLedger);
        var totals = new Dictionary<string, int>();
        var errorAgreement = new Dictionary<string, int>();
        var specCodeStats = new Dictionary<string, (int Expected, int Reported)>();
        var engineExtra = new Dictionary<string, int>();
        var byFile = new List<(string File, int Cases, Dictionary<string, int> Totals)>();
        var failures = new List<CaseOut>();
        var ledgerStale = new List<string>();
        var ledgerMismatch = new List<string>();
        var openRuns = 0;

        foreach (var file in Directory.GetFiles(directory, "*.test").OrderBy(f => f, StringComparer.Ordinal))
        {
            var root = JsonNode.Parse(File.ReadAllText(file))!.AsObject();
            var testsNode = root.ContainsKey("tests") ? root["tests"] : root["xmlViolationTests"];
            var fileTotals = new Dictionary<string, int>();
            var index = 0;
            foreach (var testNode in testsNode!.AsArray())
            {
                var test = testNode!.AsObject();
                var doubleEscaped = test["doubleEscaped"]?.GetValue<bool>() == true;
                var input = Unescape(test["input"]!.GetValue<string>(), doubleEscaped);
                var lastStartTag = test["lastStartTag"]?.GetValue<string>();
                var description = test["description"]?.GetValue<string>() ?? "";
                var expectedErrors = (test["errors"]?.AsArray() ?? [])
                    .Select(e => e!["code"]!.GetValue<string>())
                    .ToList();
                var expectedTokens = ReadExpectedTokens(test["output"]!.AsArray(), doubleEscaped);
                var initialStates = test["initialStates"] is { } states
                    ? states.AsArray().Select(n => n!.GetValue<string>()).ToList()
                    : ["Data state"];

                foreach (var initialState in initialStates)
                {
                    var (outcome, tokenSignature, errorDetail, actual) =
                        RunCase(initialState, input, lastStartTag, expectedTokens, expectedErrors,
                            specCodeStats, engineExtra);
                    Bump(totals, outcome);
                    Bump(fileTotals, outcome);
                    Bump(totals, "runs");
                    Bump(fileTotals, "runs");
                    if (outcome is "errors-differ")
                        Bump(errorAgreement, errorDetail.Contains("missing") && errorDetail.Contains("extra")
                            ? "missing-and-extra" : errorDetail.Contains("missing") ? "missing" : "extra");
                    else if (outcome is "pass")
                        Bump(errorAgreement, "agree");

                    string? ledgerVerdict = null;
                    var fileName = Path.GetFileName(file);
                    if (RunnerExclusions.ContainsKey((fileName, index)))
                    {
                        // A stale exclusion is a changed engine: the case must leave the
                        // exclusion list (never silently hide a pass).
                        if (outcome is "pass")
                        {
                            ledgerVerdict = "stale-exclusion";
                            ledgerStale.Add($"{fileName}#{index} ({initialState}): runner-excluded case passes raw");
                        }
                        else
                        {
                            ledgerVerdict = "runner-excluded";
                            Bump(totals, "runner-excluded");
                            Bump(fileTotals, "runner-excluded");
                        }
                    }
                    else if (ledger.TryGetValue((fileName, index, initialState), out var entry))
                    {
                        if (outcome is "pass")
                        {
                            ledgerVerdict = "stale";
                            ledgerStale.Add($"{fileName}#{index} ({initialState})");
                        }
                        else if (actual.SequenceEqual(entry.CorrectedOutput, StringComparer.Ordinal))
                        {
                            ledgerVerdict = "pass";
                            Bump(totals, "ledger-pass");
                            Bump(fileTotals, "ledger-pass");
                        }
                        else
                        {
                            ledgerVerdict = "mismatch";
                            ledgerMismatch.Add($"{fileName}#{index} ({initialState})");
                        }
                    }

                    if (outcome is not "pass")
                    {
                        failures.Add(new CaseOut(fileName, index, initialState, description,
                            outcome, errorDetail, tokenSignature,
                            Truncate(FormatTokens(expectedTokens)), Truncate(FormatTokens(actual))));
                        if (ledgerVerdict is null && outcome is not "errors-differ")
                            openRuns++;
                    }
                }

                index++;
            }

            byFile.Add((Path.GetFileName(file), index, fileTotals));
            Console.WriteLine($"{Path.GetFileName(file),-32} {index,5} tests  " + FormatCounts(fileTotals));
        }

        var pass = totals.GetValueOrDefault("pass");
        var errorsDiffer = totals.GetValueOrDefault("errors-differ");
        var ledgerPass = totals.GetValueOrDefault("ledger-pass");
        var excluded = totals.GetValueOrDefault("runner-excluded");
        var runs = totals.GetValueOrDefault("runs");
        var tokensDecided = pass + errorsDiffer + ledgerPass;
        Console.WriteLine();
        Console.WriteLine($"=== html5 tokenizer corpus: {runs} case/state runs ===");
        Console.WriteLine($"  tokens match:   {tokensDecided,5} of {runs} ({(runs == 0 ? 0 : 100.0 * tokensDecided / runs):F1}%)");
        Console.WriteLine($"  full pass:      {pass,5} (tokens match and errors agree)");
        Console.WriteLine($"  tokens fail:    {totals.GetValueOrDefault("tokens-fail"),5}   harness errors: {totals.GetValueOrDefault("error"),3}");
        Console.WriteLine($"  errors differ:  {errorsDiffer,5} " +
                          $"({errorAgreement.GetValueOrDefault("missing")} missing, " +
                          $"{errorAgreement.GetValueOrDefault("extra")} extra, " +
                          $"{errorAgreement.GetValueOrDefault("missing-and-extra")} both)");
        Console.WriteLine($"  ledger: {ledgerPass} accepted, {ledgerStale.Count} stale, " +
                          $"{ledgerMismatch.Count} mismatched, {unreviewedLedger} unreviewed entries");
        foreach (var stale in ledgerStale)
            Console.Error.WriteLine($"ledger stale (passes raw or a stale exclusion; entry must be regenerated): {stale}");
        foreach (var mismatch in ledgerMismatch)
            Console.Error.WriteLine($"ledger mismatch (engine != correctedOutput): {mismatch}");
        Console.WriteLine();
        Console.WriteLine("=== expected-error code agreement (spec code: expected / engine-reported) ===");
        foreach (var (code, (expected, reported)) in specCodeStats.OrderByDescending(kv => kv.Value.Expected))
            Console.WriteLine($"  {code,-62} {expected,5} / {reported,5}");
        if (engineExtra.Count > 0)
        {
            Console.WriteLine();
            Console.WriteLine("=== engine errors raised where no expected code claims them ===");
            foreach (var (code, count) in engineExtra.OrderByDescending(kv => kv.Value))
                Console.WriteLine($"  {code,-40} {count,5}");
        }

        var artifact = Path.GetFullPath(reportPath ??
            Path.Combine(ConformancePaths.EnsureArtifacts(), "html5-tokenizer-report.json"));
        WriteArtifact(artifact, totals, errorAgreement, specCodeStats, engineExtra, byFile, failures);
        Console.WriteLine();
        Console.WriteLine($"report written: {artifact}");

        if (gate)
        {
            Console.WriteLine();
            Console.WriteLine($"html5-tokenizer gate: tokens decided {tokensDecided}/{runs} " +
                              $"(+{excluded} runner-excluded U+FFFF-sentinel case)" +
                              (openRuns > 0 ? $"; {openRuns} open run(s) without a verified outcome" : "") +
                              (ledgerStale.Count > 0 ? $"; {ledgerStale.Count} stale ledger entr(y/ies)" : "") +
                              (ledgerMismatch.Count > 0 ? $"; {ledgerMismatch.Count} mismatched ledger entr(y/ies)" : ""));
            return openRuns == 0 && ledgerStale.Count == 0 && ledgerMismatch.Count == 0 ? 0 : 1;
        }

        return 0;
    }

    // ----- one case -----

    private static (string Outcome, string TokenSignature, string ErrorDetail, List<string> Actual) RunCase(
        string initialState, string input, string? lastStartTag, List<string> expectedTokens,
        List<string> expectedErrors,
        Dictionary<string, (int Expected, int Reported)> specCodeStats,
        Dictionary<string, int> engineExtra)
    {
        try
        {
            var cdataState = initialState == "CDATA section state";
            var source =
                (lastStartTag is { Length: > 0 } ? $"<{lastStartTag}>" : "") +
                (cdataState ? "<![CDATA[" : "") +
                input;
            var tokenizer = MakeTokenizer(source, cdataState, out var errors);

            // Discard the setup token(s): the emitted last-start-tag whose only job was
            // teaching the tokenizer its name (the CDATA declaration merges into the first
            // character token and needs no discard).
            if (lastStartTag is { Length: > 0 })
                tokenizer.Get();

            tokenizer.State = initialState switch
            {
                "Data state" => HtmlParseMode.PCData,
                "PLAINTEXT state" => HtmlParseMode.Plaintext,
                "RCDATA state" => HtmlParseMode.RCData,
                "RAWTEXT state" => HtmlParseMode.Rawtext,
                "Script data state" => HtmlParseMode.Script,
                "CDATA section state" => HtmlParseMode.PCData, // entered through the <![CDATA[ prefix
                _ => throw new InvalidDataException($"unknown initial state {initialState}"),
            };

            var actual = new List<string>();
            while (true)
            {
                var token = tokenizer.Get();
                if (token.Type == HtmlTokenType.EndOfFile) break;
                actual.Add(FormatToken(token));
            }

            var merged = MergeCharacters(actual);
            var expectedMerged = MergeCharacters(expectedTokens);
            var tokenMatch = merged.SequenceEqual(expectedMerged, StringComparer.Ordinal);
            var (errorsMatch, missing, extra) = CompareErrors(expectedErrors, errors, specCodeStats, engineExtra);
            var outcome = !tokenMatch ? "tokens-fail"
                : errorsMatch ? "pass"
                : "errors-differ";
            var signature = FirstDivergence(expectedMerged, merged);
            var errorDetail = "agree";
            if (!errorsMatch)
            {
                var parts = new List<string>();
                if (missing.Count > 0) parts.Add("missing: " + string.Join(", ", missing));
                if (extra.Count > 0) parts.Add("extra: " + string.Join(", ", extra));
                errorDetail = string.Join("; ", parts);
            }

            return (outcome, Truncate(signature), errorDetail, merged);
        }
        catch (Exception ex)
        {
            return ("error", ex.Message, ex.Message, []);
        }
    }

    private static (bool Match, List<string> Missing, List<string> Extra) CompareErrors(
        List<string> expectedCodes, List<(HtmlParseError Code, int Line, int Column)> engineErrors,
        Dictionary<string, (int Expected, int Reported)> specCodeStats,
        Dictionary<string, int> engineExtra)
    {
        var engineCodes = engineErrors.Select(e => e.Code).ToHashSet();
        var missing = new List<string>();
        foreach (var code in expectedCodes)
        {
            var slot = specCodeStats.GetValueOrDefault(code);
            var accepts = SpecToEngine.GetValueOrDefault(code).Engine;
            if (accepts is { Length: > 0 } && accepts.Any(engineCodes.Contains))
                specCodeStats[code] = (slot.Expected + 1, slot.Reported + 1);
            else
            {
                specCodeStats[code] = (slot.Expected + 1, slot.Reported);
                missing.Add(code);
            }
        }

        var extra = new List<string>();
        var claimed = SpecToEngine.Values.SelectMany(v => v.Engine).ToHashSet();
        foreach (var code in engineCodes.Where(code => !claimed.Contains(code)))
        {
            extra.Add(code.ToString());
            Bump(engineExtra, code.ToString());
        }

        return (missing.Count == 0 && extra.Count == 0, missing, extra);
    }

    private static string FirstDivergence(List<string> expected, List<string> actual)
    {
        for (var i = 0; i < Math.Max(expected.Count, actual.Count); i++)
        {
            var e = i < expected.Count ? expected[i] : "<eof>";
            var a = i < actual.Count ? actual[i] : "<eof>";
            if (!string.Equals(e, a, StringComparison.Ordinal))
                return $"{a}  <=>  {e}";
        }
        return "";
    }

    // ----- expected-side token reading and formatting -----

    private static List<string> ReadExpectedTokens(JsonArray output, bool doubleEscaped)
    {
        var tokens = new List<string>();
        foreach (var node in output)
        {
            var parts = node!.AsArray();
            var kind = parts[0]!.GetValue<string>();
            switch (kind)
            {
                case "Character":
                    tokens.Add("Character " + Quote(Unescape(parts[1]!.GetValue<string>(), doubleEscaped)));
                    break;
                case "StartTag":
                {
                    var name = Unescape(parts[1]!.GetValue<string>(), doubleEscaped);
                    var attributes = parts[2]!.AsObject()
                        .Select(a => $"{a.Key}={Quote(Unescape(a.Value!.GetValue<string>(), doubleEscaped))}")
                        .ToList();
                    var selfClosing = parts.Count > 3 && parts[3]!.GetValue<bool>();
                    tokens.Add(
                        $"StartTag {name} [{string.Join(" ", attributes)}]{(selfClosing ? " self-closing" : "")}");
                    break;
                }
                case "EndTag":
                    tokens.Add("EndTag " + Unescape(parts[1]!.GetValue<string>(), doubleEscaped));
                    break;
                case "Comment":
                    tokens.Add("Comment " + Quote(Unescape(parts[1]!.GetValue<string>(), doubleEscaped)));
                    break;
                case "ProcessingInstruction":
                    tokens.Add($"ProcessingInstruction {parts[1]!.GetValue<string>()} " +
                               Quote(Unescape(parts[2]!.GetValue<string>(), doubleEscaped)));
                    break;
                case "DOCTYPE":
                {
                    var name = parts[1] is null ? "<missing>" : Unescape(parts[1]!.GetValue<string>(), doubleEscaped);
                    var publicId = parts[2] is null ? "<missing>" : Quote(Unescape(parts[2]!.GetValue<string>(), doubleEscaped));
                    var systemId = parts[3] is null ? "<missing>" : Quote(Unescape(parts[3]!.GetValue<string>(), doubleEscaped));
                    var correctness = parts[4]!.GetValue<bool>();
                    tokens.Add($"DOCTYPE name={name} public={publicId} system={systemId} correctness={correctness}");
                    break;
                }
                default:
                    throw new InvalidDataException($"unknown expected token kind {kind}");
            }
        }

        return tokens;
    }

    private static string FormatToken(HtmlToken token)
    {
        switch (token.Type)
        {
            case HtmlTokenType.Character:
                return "Character " + Quote(token.Data);
            case HtmlTokenType.Comment:
                return "Comment " + Quote(token.Data);
            case HtmlTokenType.StartTag:
            {
                var tag = token.AsTag();
                return $"StartTag {tag.Name} [{string.Join(" ", tag.Attributes.Select(a => $"{a.Name}={Quote(a.Value)}"))}]" +
                       (tag.IsSelfClosing ? " self-closing" : "");
            }
            case HtmlTokenType.EndTag:
                // The corpus format carries no attributes on EndTag expectations (the spec's
                // tokenizer drops them with a parse error).
                return "EndTag " + token.Name;
            case HtmlTokenType.Doctype:
            {
                var doctype = (HtmlDoctypeToken)token;
                return $"DOCTYPE name={(doctype.Name.Length == 0 ? "<missing>" : doctype.Name)} " +
                       $"public={(doctype.IsPublicIdentifierMissing ? "<missing>" : Quote(doctype.PublicIdentifier))} " +
                       $"system={(doctype.IsSystemIdentifierMissing ? "<missing>" : Quote(doctype.SystemIdentifier))} " +
                       $"correctness={!doctype.IsQuirksForced}";
            }
            default:
                throw new InvalidDataException($"unexpected token type {token.Type}");
        }
    }

    /// <summary>Coalesces adjacent Character tokens and drops empty ones — the format's own
    /// normalization, applied to both sides so token-splitting differences cannot masquerade
    /// as mismatches.</summary>
    private static List<string> MergeCharacters(List<string> tokens)
    {
        var merged = new List<string>();
        var pending = new System.Text.StringBuilder();
        foreach (var token in tokens)
        {
            if (token.StartsWith("Character ", StringComparison.Ordinal))
            {
                var data = token[("Character ".Length + 1)..^1]; // between the quotes
                if (data.Length > 0) pending.Append(data);
                continue;
            }
            if (pending.Length > 0) merged.Add("Character " + Quote(pending.ToString()));
            pending.Clear();
            merged.Add(token);
        }
        if (pending.Length > 0) merged.Add("Character " + Quote(pending.ToString()));
        return merged;
    }

    private static string Quote(string value) => "\"" + value + "\"";

    /// <summary>The html5lib double-escaped convention: the only extra unescaping is
    /// \uHHHH → code point, applied after the JSON decode (a surrogate pair reunites; a
    /// lone surrogate becomes U+FFFD, which cannot exist in a string).</summary>
    private static string Unescape(string value, bool doubleEscaped)
    {
        if (!doubleEscaped || !value.Contains(@"\u", StringComparison.Ordinal))
            return value;

        var builder = new System.Text.StringBuilder(value.Length);
        var position = 0;
        while (position < value.Length)
        {
            if (TryReadEscape(value, position) is { } unit)
            {
                position += 6;
                var low = TryReadEscape(value, position);
                if (unit is >= 0xD800 and <= 0xDBFF && low is >= 0xDC00 and <= 0xDFFF)
                {
                    builder.Append((char)unit);
                    builder.Append((char)low!.Value);
                    position += 6;
                }
                else if (unit is >= 0xD800 and <= 0xDFFF)
                {
                    builder.Append("\uFFFD");
                }
                else
                {
                    builder.Append((char)unit);
                }
            }
            else
            {
                builder.Append(value[position]);
                position++;
            }
        }

        return builder.ToString();

        static ushort? TryReadEscape(string text, int at) =>
            at + 6 <= text.Length && text[at] == '\\' && text[at + 1] == 'u' &&
            ushort.TryParse(text.Substring(at + 2, 4),
                System.Globalization.NumberStyles.HexNumber, System.Globalization.CultureInfo.InvariantCulture,
                out var parsed)
                ? parsed
                : null;
    }

    private static string FormatTokens(List<string> tokens) => string.Join("; ", tokens);

    // ----- the spec-code map: html5lib tokenizer error codes onto the engine's set -----
    // Engine sets list every engine code that may legitimately report the spec condition;
    // the engine collapses several spec codes into one raise site and discriminates the
    // doctype keyword/quote codes by character class rather than by spec code. An empty set
    // records a condition the engine never reports (several are living-standard-only input
    // checks the 2014 REC does not define).

    internal static readonly Dictionary<string, (HtmlParseError[] Engine, string Note)> SpecToEngine = new()
    {
        ["abrupt-closing-of-empty-comment"] = ([HtmlParseError.TagClosedWrong],
            "<!--> / <!--->: comment-start(-dash) '>' raises TagClosedWrong"),
        ["abrupt-doctype-public-identifier"] = ([HtmlParseError.EOF],
            "EOF inside the quoted public identifier raises EOF"),
        ["abrupt-doctype-system-identifier"] = ([HtmlParseError.EOF],
            "EOF inside the quoted system identifier raises EOF"),
        ["absence-of-digits-in-numeric-character-reference"] = ([HtmlParseError.CharacterReferenceWrongNumber],
            "&#x; / &#;: raises CharacterReferenceWrongNumber"),
        ["cdata-in-html-content"] = ([HtmlParseError.UndefinedMarkupDeclaration],
            "<![CDATA[ outside foreign content falls to the bogus-comment branch"),
        ["character-reference-outside-unicode-range"] = ([HtmlParseError.CharacterReferenceInvalidNumber],
            "out-of-range numbers raise CharacterReferenceInvalidNumber and insert U+FFFD"),
        ["control-character-in-input-stream"] = ([], "living-standard input check; the engine is silent"),
        ["control-character-reference"] = ([HtmlParseError.CharacterReferenceInvalidCode],
            "C0/C1 control references raise CharacterReferenceInvalidCode"),
        ["duplicate-attribute"] = ([HtmlParseError.AttributeDuplicateOmitted],
            "raised when the duplicate attribute is dropped"),
        ["end-tag-with-attributes"] = ([HtmlParseError.EndTagCannotHaveAttributes], ""),
        ["end-tag-with-trailing-solidus"] = ([HtmlParseError.EndTagCannotBeSelfClosed], ""),
        ["eof-before-tag-name"] = ([HtmlParseError.EOF], "'<' at EOF raises EOF"),
        ["eof-in-cdata"] = ([], "the engine's CDATA state emits its text at EOF without an error"),
